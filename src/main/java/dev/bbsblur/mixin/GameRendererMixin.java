package dev.bbsblur.mixin;

import dev.bbsblur.client.BlurRenderer;
import net.minecraft.client.render.GameRenderer;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(GameRenderer.class)
public class GameRendererMixin
{
    /** Right after the world is drawn and before the HUD / BBS UI are drawn on top. */
    @Inject(
        method = "render",
        at = @At(
            value = "INVOKE",
            target = "Lnet/minecraft/client/render/GameRenderer;renderWorld(FJLnet/minecraft/client/util/math/MatrixStack;)V",
            shift = At.Shift.AFTER
        )
    )
    private void bbsblur$afterWorld(float tickDelta, long startTime, boolean tick, CallbackInfo info)
    {
        BlurRenderer.render();
    }
}
